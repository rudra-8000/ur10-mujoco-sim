def P3(name):
    x, z = PIV[name]
    return np.array([x * 1e-3, 0.0, z * 1e-3])


# ---------------- planar six-bar solver (reference for verification + cam<->gap table) ----------------
def circ_int(c0, r0, c1, r1, prefer):
    d = np.linalg.norm(c1 - c0)
    if d > r0 + r1 or d < abs(r0 - r1) or d == 0:
        return None
    a = (r0 * r0 - r1 * r1 + d * d) / (2 * d); h2 = r0 * r0 - a * a
    if h2 < 0:
        return None
    e = (c1 - c0) / d; n = np.array([-e[1], e[0]]); h = np.sqrt(h2)
    cands = [c0 + a * e + h * n, c0 + a * e - h * n]
    return min(cands, key=lambda p: np.linalg.norm(p - prefer))


def rot(v, a):
    c, s = np.cos(a), np.sin(a)
    return np.array([c * v[0] - s * v[1], s * v[0] + c * v[1]])


def finger_pose(side, dtheta, prev=None):
    """tip-body pose (rotation dphi [rad] about the IR-tip pivot, pivot position) for a cam rotation dtheta from the exported pose.
    all in (x_g, z_g) mm.  prev = dict of previous branch points."""
    A = {k: np.array(PIV[k + "_" + side]) for k in ("cam_pin", "dr_ir", "ir_base", "ir_tip", "or_base", "or_tip")}
    C = np.array(PIV["cam_axis"])
    K = C + rot(A["cam_pin"] - C, dtheta)
    Ld = np.linalg.norm(A["dr_ir"] - A["cam_pin"])
    rn = np.linalg.norm(A["dr_ir"] - A["ir_base"])
    N = circ_int(A["ir_base"], rn, K, Ld, prev["N"] if prev else A["dr_ir"])
    if N is None:
        return None
    n0 = A["dr_ir"] - A["ir_base"]; n1 = N - A["ir_base"]
    dpsi = np.arctan2(n1[1], n1[0]) - np.arctan2(n0[1], n0[0])
    P1 = A["ir_base"] + rot(A["ir_tip"] - A["ir_base"], dpsi)
    t0 = A["or_tip"] - A["ir_tip"]; lt = np.linalg.norm(t0); Lo = np.linalg.norm(A["or_tip"] - A["or_base"])
    P2 = circ_int(A["or_base"], Lo, P1, lt, prev["P2"] if prev else A["or_tip"])
    if P2 is None:
        return None
    dphi = np.arctan2(*(P2 - P1)[::-1]) - np.arctan2(t0[1], t0[0])
    return dict(N=N, P1=P1, P2=P2, dphi=dphi, side=side)


def pad_center_z(side, pose):
    """z_g (mm) of the pad's inner face at the pad centre for a given tip pose (rigid about P1)"""
    A = np.array(PIV["ir_tip_" + side])
    face_y = PAD_FACE_A[side] - O_A[1]     # Tip_Support inner face (contact surface)
    xc = 0.5 * (PAD_X_A[0] + PAD_X_A[1]) - O_A[0]
    p0 = np.array([xc, face_y])
    return (pose["P1"] + rot(p0 - A, pose["dphi"]))[1]


def gap_table():
    def sweep(degs):
        prev = {"L": None, "R": None}; out = []
        for dd in degs:
            pL = finger_pose("L", np.radians(dd), prev["L"]); pR = finger_pose("R", np.radians(dd), prev["R"])
            if pL is None or pR is None:
                break
            prev = {"L": pL, "R": pR}
            out.append((float(dd), float(pad_center_z("L", pL) - pad_center_z("R", pR))))    # TRUE pad gap (pads included)
        return out
    return sorted(sweep(np.arange(-1, -200.01, -1.0)) + sweep(np.arange(0, 90.01, 1.0)))


# ---------------- MJCF ----------------
def fmt(v, n=6):
    return " ".join(f"{x:.{n}f}" for x in v)


def build():
    MESHES.mkdir(parents=True, exist_ok=True)
    body_meshes, props = {}, {}
    for body, parts in PARTS.items():
        tris_all = []
        for part in parts:
            t = to_G(load_stl(SRC / f"{PREFIX}{part}.STL"))
            name = part.replace(" ", "_").replace(".", "_")
            # MuJoCo merges identical vertices and smooths normals across them (2.3.x has no flat-shading option), which makes flat-faced
            # CAD parts render as blobs.  Pull each triangle's vertices 5 um toward its centroid so vertices stay unique => flat shading.
            cen = t.mean(axis=1, keepdims=True)
            write_stl(MESHES / f"{name}.stl", t + (cen - t) * 0.0004 / np.maximum(np.linalg.norm(cen - t, axis=2, keepdims=True), 1e-9) * 0.01)
            body_meshes.setdefault(body, []).append(name)
            tris_all.append(t)
        T = np.concatenate(tris_all)
        vol, cen, I = mesh_mass_props(T) if body not in ("base",) else (None, None, None)
        props[body] = (vol, cen, I)
    return body_meshes, props


def mjcf(gap):
    body_meshes, props = build()
    dd = np.array([g[0] for g in gap]); gp = np.array([g[1] for g in gap])
    i_open = int(np.argmax(gp))
    valid_closed = dd[gp > 0.5]
    lo_deg, hi_deg = float(valid_closed.min()), float(dd[i_open]) - 3.0     # stay 3 deg short of the toggle (dead) point
    rng = (np.radians(lo_deg), np.radians(hi_deg))
    out = []
    A = out.append
    A('<mujoco model="pincopen_try3">')
    A('  <!-- GENERATED by ur10sim/build_pincopen.py (gripper revision try3); edit the generator, not this file -->')
    A('  <compiler angle="radian" meshdir="meshes" autolimits="true"/>')
    A('  <option timestep="0.001" integrator="implicitfast" impratio="10" noslip_iterations="3"/>')
    A('  <default>')
    A('    <joint armature="2e-5" damping="0.005"/>')
    A('    <default class="visual"><geom type="mesh" contype="0" conaffinity="0" group="1" rgba="0.85 0.85 0.88 1"/></default>')
    A('    <default class="pad"><geom type="box" group="3" friction="1.2 0.02 0.002" condim="4" solref="0.004 1" solimp="0.95 0.99 0.001" margin="0.0005" rgba="0.1 0.6 0.1 0.3"/></default>')
    A('  </default>')
    A('  <asset>')
    for b, ms in body_meshes.items():
        for m in ms:
            A(f'    <mesh name="{m}" file="{m}.stl"/>')
    A('  </asset>')

    def inertial(body, pivot):
        vol, cen, I = props[body]
        if vol is None:   # base: mass only, COM at origin-ish (approximate; refine when mount/servo CAD is added)
            return f'<inertial pos="0.0 0 0" mass="{MASS[body]:.6f}" diaginertia="1e-4 1e-4 1e-4"/>'
        rho = MASS[body] / vol
        Ic = I * rho
        return (f'<inertial pos="{fmt(cen - pivot)}" mass="{MASS[body]:.6f}" '
                f'fullinertia="{Ic[0,0]:.4e} {Ic[1,1]:.4e} {Ic[2,2]:.4e} {Ic[0,1]:.4e} {Ic[0,2]:.4e} {Ic[1,2]:.4e}"/>')

    def geoms(body, pivot):
        return "\n".join(f'        <geom class="visual" mesh="{m}" pos="{fmt(-pivot)}"/>' for m in body_meshes[body])

    # dr/ir/tip/or hinges had NO range at all (limited="false") -- a real gripper's pivots have hard
    # mechanical stops; without them, nothing stops MuJoCo's loop-closure solver (the <connect> equality
    # constraints below) from settling into the OTHER valid solution for a closed 4-bar linkage under a
    # hard enough perturbation (fast/asymmetric contact) -- same joint angles, loop-closure still
    # satisfied ("kinematically valid"), but the finger is flipped ~180 deg about its own axis. Measured
    # normal operating range across 6 full open/close cycles (see CHANGELOG.md 2026-09-29), +-0.5 rad
    # margin -- comfortably covers real operation, nowhere near the ~3.14 rad needed to reach the flip.
    LINK_RANGE = {
        "dr":  (-1.25, 2.00),
        "ir":  (-1.40, 1.50),
        "tip": (-2.05, 1.70),
        "or":  (-1.55, 1.75),
    }

    def hinge(name, rng=None, damping=0.001):
        r = f' range="{rng[0]:.5f} {rng[1]:.5f}" limited="true"' if rng else ""
        return f'<joint name="{name}" type="hinge" axis="0 -1 0"{r} damping="{damping}"/>'

    A('  <worldbody>')
    A('    <body name="pincopen_base" pos="0 0 0">')
    A('      ' + inertial("base", np.zeros(3)))
    A("\n".join(f'      <geom class="visual" mesh="{m}"/>' for m in body_meshes["base"]))
    A('      <site name="jaw_center" pos="0.0850 0 0.0" size="0.002" rgba="1 0 0 1"/>')
    cam_p = P3("cam_axis")
    A(f'      <body name="cam" pos="{fmt(cam_p)}">')
    A('        ' + inertial("cam", cam_p)); A(f'        {hinge("cam_joint", rng, 0.02)}'); A(geoms("cam", cam_p))
    for s in ("L", "R"):
        pin = P3("cam_pin_" + s)
        A(f'        <body name="dr_{s}" pos="{fmt(pin - cam_p)}">')
        A('          ' + inertial("dr_" + s, pin)); A(f'          {hinge("dr_" + s + "_joint", LINK_RANGE["dr"])}'); A(geoms("dr_" + s, pin)); A('        </body>')
    A('      </body>')
    for s in ("L", "R"):
        irp = P3("ir_base_" + s)
        A(f'      <body name="ir_{s}" pos="{fmt(irp)}">')
        A('        ' + inertial("ir_" + s, irp)); A(f'        {hinge("ir_" + s + "_joint", LINK_RANGE["ir"])}'); A(geoms("ir_" + s, irp))
        tp = P3("ir_tip_" + s)
        A(f'        <body name="tip_{s}" pos="{fmt(tp - irp)}">')
        A('          ' + inertial("tip_" + s, tp)); A(f'          {hinge("tip_" + s + "_joint", LINK_RANGE["tip"])}'); A(geoms("tip_" + s, tp))
        yface = PAD_FACE_A[s]
        # pad box: inner face at yface, 4 mm thick toward the outside of the jaw
        sign = +1 if s == "L" else -1     # L finger is at larger y_a; the rubber extends from the contact face AWAY from the jaw centre
        cy_a = yface + sign * PAD_THICK_MM / 2
        centre = to_G(np.array([0.5 * (PAD_X_A[0] + PAD_X_A[1]), cy_a, 0.5 * (PAD_Z_A[0] + PAD_Z_A[1])]))
        half = np.array([0.5 * (PAD_X_A[1] - PAD_X_A[0]), 0.5 * (PAD_Z_A[1] - PAD_Z_A[0]), PAD_THICK_MM / 2]) * 1e-3      # (x, y_g(=za), z_g(=ya))
        A(f'          <geom class="pad" name="pad_{s}" pos="{fmt(centre - tp)}" size="{half[0]:.5f} {half[1]:.5f} {half[2]:.5f}"/>')
        A('        </body>'); A('      </body>')
        orp = P3("or_base_" + s)
        A(f'      <body name="or_{s}" pos="{fmt(orp)}">')
        A('        ' + inertial("or_" + s, orp)); A(f'        {hinge("or_" + s + "_joint", LINK_RANGE["or"])}'); A(geoms("or_" + s, orp)); A('      </body>')
    A('    </body>'); A('  </worldbody>')
    A('  <equality>')
    for s in ("L", "R"):
        A(f'    <connect name="loop_dr_ir_{s}" body1="dr_{s}" body2="ir_{s}" anchor="{fmt(P3("dr_ir_" + s) - P3("cam_pin_" + s))}" solref="0.006 1" solimp="0.95 0.99 0.001"/>')
        A(f'    <connect name="loop_or_tip_{s}" body1="or_{s}" body2="tip_{s}" anchor="{fmt(P3("or_tip_" + s) - P3("or_base_" + s))}" solref="0.006 1" solimp="0.95 0.99 0.001"/>')
    A('  </equality>')
    A('  <actuator>')
    A(f'    <general name="cam_act" joint="cam_joint" gainprm="60" biastype="affine" biasprm="0 -60 -1.0" ctrlrange="{rng[0]:.5f} {rng[1]:.5f}" forcerange="-1 1"/>')
    A('  </actuator>'); A('</mujoco>')
    return "\n".join(out), dict(cam_range_rad=[float(rng[0]), float(rng[1])])


def rot_to_rpy(R):
    p = np.arcsin(np.clip(-R[2, 0], -1, 1))
    if abs(np.cos(p)) > 1e-6:
        return np.array([np.arctan2(R[2, 1], R[2, 2]), p, np.arctan2(R[1, 0], R[0, 0])])
    return np.array([0.0, p, np.arctan2(-R[0, 1], R[1, 1])])


def urdf(cam_range):
    """tree-only URDF, link frame = world-aligned hinge frame at the pivot; meshes are already in gripper-frame metres."""
    body_meshes, props = build()
    piv = {"base_link": np.zeros(3), "cam": P3("cam_axis")}
    parent = {"cam": "base_link"}
    for s in ("L", "R"):
        piv.update({f"dr_{s}": P3("cam_pin_" + s), f"ir_{s}": P3("ir_base_" + s), f"tip_{s}": P3("ir_tip_" + s), f"or_{s}": P3("or_base_" + s)})
        parent.update({f"dr_{s}": "cam", f"ir_{s}": "base_link", f"tip_{s}": f"ir_{s}", f"or_{s}": "base_link"})
    L = ['<?xml version="1.0"?>',
         '<!-- GENERATED by build_pincopen.py (gripper revision try3). TREE ONLY: closed loops (dr_ir_*: dr_L/R <-> ir_L/R, or_tip_*: or_L/R <-> tip_L/R)',
         '     cannot be expressed in URDF; see pincopen_meta.json "loop_closures"; pincopen.xml has them as MuJoCo connect constraints.',
         '     Planar mechanism in the x-z plane, every joint revolute about -Y, link frames world-aligned at the pivots, units m. -->',
         '<robot name="pincopen_try3">']
    for name, pv in piv.items():
        key = "base" if name == "base_link" else name
        m = MASS[key]
        vol, cen, I = props[key]
        if vol is None:
            com, Ic = np.zeros(3), np.diag([1e-4] * 3)
        else:
            com, Ic = cen - pv, I * (m / vol)
        vis = "".join(f'<visual><origin xyz="{fmt(-pv)}"/><geometry><mesh filename="meshes/{mm}.stl"/></geometry></visual>' for mm in body_meshes[key])
        L.append(f'  <link name="{name}"><inertial><origin xyz="{fmt(com)}"/><mass value="{m:.6f}"/>'
                 f'<inertia ixx="{Ic[0,0]:.4e}" ixy="{Ic[0,1]:.4e}" ixz="{Ic[0,2]:.4e}" iyy="{Ic[1,1]:.4e}" iyz="{Ic[1,2]:.4e}" izz="{Ic[2,2]:.4e}"/></inertial>{vis}</link>')
    for name, par in parent.items():
        lim = (f'<limit lower="{cam_range[0]:.5f}" upper="{cam_range[1]:.5f}" effort="3" velocity="10"/>' if name == "cam"
               else '<limit lower="-3.14159" upper="3.14159" effort="1" velocity="10"/>')
        L.append(f'  <joint name="{name}_joint" type="revolute"><parent link="{par}"/><child link="{name}"/>'
                 f'<origin xyz="{fmt(piv[name] - piv[par])}" rpy="0 0 0"/><axis xyz="0 -1 0"/>{lim}</joint>')
    L.append('</robot>')
    return "\n".join(L)


def frac_map(tab):
    """recorded gripper fraction (0 open .. 1 closed) <-> cam angle:  frac = (a_open - cam) / span, FITTED from the two grasp plateaus
    (2 equations, 2 unknowns): frac 0.569 holds the 41.5 mm square section, 0.505 holds the 50 mm round section.  Everything else
    (open gap at frac 0, frac at which the rubber pads meet) is then a PREDICTION to compare with the data (max recorded 0.93)."""
    tab = np.array(tab)
    imax = int(np.argmax(tab[:, 1]))
    br = tab[: imax + 1]                                   # ascending angle, gap increasing up to the toggle point
    ang = lambda gap: float(np.interp(gap, br[:, 1], br[:, 0]))
    a_sq, a_rd = ang(PEG_SQ_MM), ang(PEG_ROUND_MM)         # cam angle where the gap equals each peg section
    span = (a_rd - a_sq) / (PLATEAU_CIRC_TASK - PLATEAU_SQR_TASK)
    a_open = a_rd + PLATEAU_SQR_TASK * span
    fr = np.linspace(0, 1, 21)
    cam = a_open - fr * span
    gap = np.minimum.accumulate(np.maximum(np.interp(cam, tab[:, 0], tab[:, 1]), 0.0))    # monotone: past pad contact the gap stays ~0
    at = lambda f: float(np.interp(a_open - f * span, tab[:, 0], tab[:, 1]))
    contact = float(tab[tab[:, 1] > 0.5][:, 0].min())
    return dict(a_open_deg=float(a_open), span_deg=float(span), implied_cam_to_servo_ratio=float(span / 119.0), servo_span_deg_from_recorder=119.0,
                frac=[float(x) for x in fr], cam_deg=[float(x) for x in cam], gap_mm=[float(x) for x in gap],
                PREDICTED_gap_mm_at_frac_0=at(0.0), PREDICTED_frac_at_pad_contact=float((a_open - contact) / span),
                data_max_recorded_frac=0.93, gap_mm_at_plateau_circle_task=at(PLATEAU_CIRC_TASK), gap_mm_at_plateau_square_task=at(PLATEAU_SQR_TASK))


def mount_info():
    """flange -> gripper-frame transform.
    Orientation (user): at home (joints 0,-90,90,-90,-90,90) the hinge ('pin') axes point toward the robot base, i.e. along the base x axis.
    FK at home gives flange x_f = +x_base, y_f = -y_base, z_f = -z_base (tool pointing down).  Tool axis x_g = z_f, hinge axis
    y_g = s*x_f, jaw axis z_g = x_g x y_g = s*y_f.  s=+1: +y_g points toward the base (assumed; flip MOUNT_SIGN otherwise).
    Position: the flange plane is taken as the BACK FACE of the Mount ARM plate (x_a = 21.8 mm -> x_g = -55.9 mm), on the plate's centre
    line (y_g = -1.1 mm, z_g = 0).  Cross-check: the 145 mm TCP then lands at x_g = 89.1 mm, 3 mm short of the fingertip end (92.3 mm), and
    the dataset grasps (TCP z ~ 6 mm above the table while holding a lying peg, i.e. pad centre ~9 mm higher) agree with that."""
    sgn = MOUNT_SIGN
    R = np.array([[0.0, sgn, 0.0], [0.0, 0.0, sgn], [1.0, 0.0, 0.0]])       # columns = x_g, y_g, z_g expressed in the flange frame
    xf_g = (MOUNT_ARM_BACK_X_A - O_A[0]) * 1e-3                              # flange plane x in the gripper frame (m), negative
    f_in_g = np.array([xf_g, -1.1e-3, 0.0])                                  # flange origin in G
    p_fg = R @ (-f_in_g)                                                     # G origin in F = R_FG @ (-p_GF)
    tcp_x_g = xf_g * 1e3 + 145.0
    return dict(sign=sgn, R_flange_gripper=R.tolist(), p_flange_gripper_m=[float(v) for v in p_fg], tcp_offset_mm=145.0,
                flange_plane_x_g_mm=xf_g * 1e3, tcp_x_g_mm=tcp_x_g, fingertip_end_x_g_mm=170.0 - O_A[0],
                pad_centre_x_g_mm=0.5 * (PAD_X_A[0] + PAD_X_A[1]) - O_A[0],
                note="orientation sign ASSUMED; position from the Mount ARM back face, see docstring/README")


