"""Generate the MuJoCo model (+ tree URDF + metadata) of the PincOpen gripper, revision TRY3.

Source geometry: cad/PincOpen_Gripper/solidworks/try2/print_3/TRY2_ASS - *.STL -- part meshes exported IN ASSEMBLY
COORDINATES (mm).  try3 is identical to try2 for every linkage part (cmp of the .SLDPRT files: Cam, Driving/Internal/
External/Distal rods, Distal_Shell, Tip_Support, Top_Plate, Part1, Mount ARM ... are byte-identical).  Per the user the robot
uses the try2 `Removable_Tip` (NOT the xense tip); `Tip_Support` is the rubber pad that goes onto the Removable_Tip, so the
contact surface = the inner face of Tip_Support.  The SolidWorks URDF export
(URDF/try_1) is NOT used: it is the older try1 linkage (different lever lengths) and has degenerate joints.

Mechanism (per finger, planar; assembly x = finger direction, y = pinch direction, z = hinge axis):
  servo -> CAM (2 pins 180 deg apart, r 11.0 mm) -> DR (32.6 mm) -> IR (rigid rocker pinned to the base; arms 16.4 / 44.9 mm)
        -> Tip body (Distal_Rod + Distal_Shell + Tip_Support + Removable_Tip, rigid; pinned to the IR far end)
  OR (external rod, 40.0 mm, pinned to the base) closes the loop on the tip body 11.5 mm from the IR pivot.
  1 DOF per finger; both driven by one cam joint.  Unlike try1 it is NOT an exact parallelogram (base pivots 13.7 mm apart vs
  11.5 mm on the tip), so the tips rotate a little while closing (measured in verify_pincopen.py).
Pivots were measured as circular through-holes in the meshes (find_pivots.py).  Loops = MuJoCo `connect` constraints.

Gripper frame G (metres): origin on the cam axis at mid finger-plane; +x = fingers/tool axis, z = jaw (pinch) direction
(fingers at z ~ -33..+40 mm), y = hinge axis (y_g = -(z_assembly - 50.5)).  cam_joint > 0 = CCW in the x-z plane.
"""
