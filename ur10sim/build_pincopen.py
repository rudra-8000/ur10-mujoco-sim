def load_stl(path):
    import re
    b = Path(path).read_bytes()
    if b[:5] == b"solid" and b"facet" in b[:400]:
        return np.array(re.findall(rb"vertex\s+(\S+)\s+(\S+)\s+(\S+)", b), dtype=float).reshape(-1, 3, 3)
    n = struct.unpack("<I", b[80:84])[0]
    dt = np.dtype([("n", "<3f4"), ("v", "<9f4"), ("a", "<u2")])
    return np.frombuffer(b, dtype=dt, count=n, offset=84)["v"].reshape(-1, 3, 3).astype(float)


def write_stl(path, tris):
    tris = np.asarray(tris, np.float32)
    n = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0]); n /= np.linalg.norm(n, axis=1, keepdims=True) + 1e-20
    with open(path, "wb") as f:
        f.write(b"pincopen try3 generated by build_pincopen.py".ljust(80, b" "))
        f.write(struct.pack("<I", len(tris)))
        for t, nn in zip(tris, n):
            f.write(struct.pack("<12fH", *nn, *t.reshape(-1), 0))


def to_G(pts_mm):
    """assembly (xa, ya, za) [mm] -> gripper frame (x, y, z) [m].  x_g = xa - 77.7, y_g = -(za - 50.5), z_g = ya - 77.4"""
    p = np.asarray(pts_mm, float) - O_A
    return np.stack([p[..., 0], -p[..., 2], p[..., 1]], -1) * 1e-3


def mesh_mass_props(tris_m):
    """volume, centroid, inertia about the centroid per unit density (SI, closed mesh)"""
    v0, v1, v2 = tris_m[:, 0], tris_m[:, 1], tris_m[:, 2]
    d = np.einsum("ij,ij->i", v0, np.cross(v1, v2))
    vol = d.sum() / 6
    cen = ((v0 + v1 + v2) / 4 * d[:, None]).sum(0) / 6 / vol
    # covariance integral via tetrahedra about origin
    C = np.zeros((3, 3))
    for a, b, c, dd in zip(v0, v1, v2, d):
        V = np.array([a, b, c])
        S = V.T @ V + np.outer(V.sum(0), V.sum(0))
        C += dd / 120 * S
    I0 = np.trace(C) * np.eye(3) - C
    I = I0 - vol * ((cen @ cen) * np.eye(3) - np.outer(cen, cen))
    return vol, cen, I


